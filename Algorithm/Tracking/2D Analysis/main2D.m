% Clear the workspace and close every open figure.
clear all, close all

% Set the sampling interval of the synthetic 2D model in seconds.
timestep = 1;
% Set the standard deviation of the measurement noise in Hz.
sigma_fd = 50e1;

% Generate the 2D Doppler truth, its first derivative, and its second derivative.
[t,fd_truth, dfdt, d2fdt2] = generateOWDoppler2DModel(timestep,1, -1, -1, -1, -1);

% Add Gaussian noise to the ground-truth Doppler sequence.
[fd] = addNoise(fd_truth, sigma_fd);

% Create a quick-look figure of the noisy S-curve in kHz.
figure
% Plot the noisy Doppler measurements converted from Hz to kHz.
plot(t, fd*1e-3)

%% Assumptions on studies
% -Only 120 s of signal -> Realistic with previously captured signals
% 
% -Time selected randomly from any interval comprised between the 'shoulders'
% of the S curve -> Disregard asymptotes, which do not provide as much
% information.


%% Study 1: Effect of Q/R ratio (process noise scale) + compare velocity and acceleration models.
% Create a logarithmic sweep of process-noise values.
q = logspace(-2,2,10);
% Preallocate the Doppler estimates produced by the 2-state filter.
fd_vel = zeros(length(fd), length(q));
% Preallocate the Doppler estimates produced by the 3-state filter.
fd_acc = zeros(length(fd), length(q));

% Preallocate the Doppler-rate estimates produced by the 2-state filter.
fddot_vel = zeros(length(fd), length(q));
% Preallocate the Doppler-rate estimates produced by the 3-state filter.
fddot_acc = zeros(length(fd), length(q));

% Preallocate the final covariance terms kept from the 2-state filter.
vel_cov = zeros(2, length(q));
% Preallocate the final covariance terms kept from the 3-state filter.
acc_cov = zeros(2, length(q));

% Preallocate the Doppler and Doppler-rate RMSE values of the 2-state filter.
vel_rmse = zeros(2, length(q));
% Preallocate the Doppler and Doppler-rate RMSE values of the 3-state filter.
acc_rmse = zeros(2, length(q));

% Sweep the process-noise scale and store the filter outputs for each value.
for i = 1:1:length(q)
    % Run the 2-state linear Kalman filter for the current process noise.
    output_vel = linearKF(fd, timestep, q(i), sigma_fd, d2fdt2, 0);
    % Store the Doppler estimate of the 2-state filter.
    fd_vel(:,i) = output_vel.fdEst;
    % Store the Doppler-rate estimate of the 2-state filter.
    fddot_vel(:,i) = output_vel.fdDotEst;
    % Store the final covariance terms of the 2-state filter.
    vel_cov(:,i) = output_vel.covarianceHistory(:,end);
    % Compute the Doppler RMSE of the 2-state filter.
    vel_rmse(1,i) = rmse(fd_truth, fd_vel(:,i));
    % Compute the Doppler-rate RMSE of the 2-state filter.
    vel_rmse(2,i) = rmse(dfdt, fddot_vel(2:end,i));

    % Run the 3-state linear Kalman filter for the current process noise.
    output_acc = linearKF(fd, timestep, q(i), sigma_fd, d2fdt2, 1);
    % Store the Doppler estimate of the 3-state filter.
    fd_acc(:,i) = output_acc.fdEst;
    % Store the Doppler-rate estimate of the 3-state filter.
    fddot_acc(:,i) = output_acc.fdDotEst;
    % Store the first two final covariance terms of the 3-state filter.
    acc_cov(:,i) = output_acc.covarianceHistory(1:2,end);
    % Compute the Doppler RMSE of the 3-state filter.
    acc_rmse(1,i) = rmse(fd_truth, fd_acc(:,i));
    % Compute the Doppler-rate RMSE of the 3-state filter.
    acc_rmse(2,i) = rmse(dfdt, fddot_acc(2:end,i));
end

% Create a figure comparing all 2-state Doppler estimates with the truth.
figure()
% Plot every 2-state Doppler estimate generated by the process-noise sweep.
plot(t, fd_vel)
% Keep the figure active so the truth can be overlaid.
hold on
% Overlay the ground-truth Doppler reference.
plot(t, fd_truth, 'LineWidth',2, 'LineStyle','--')
% Label the curves associated with the selected process-noise values.
legend('q = 0.01', 'q = 0.1', 'q = 1', 'q = 10', 'q = 100')

% Create a figure comparing all 2-state Doppler-rate estimates with the truth.
figure()
% Plot every 2-state Doppler-rate estimate generated by the process-noise sweep.
plot(t, fddot_vel)
% Keep the figure active so the truth can be overlaid.
hold on
% Overlay the ground-truth Doppler-rate reference.
plot(t(2:end), dfdt, 'LineWidth',2, 'LineStyle','--')
% Label the curves associated with the selected process-noise values.
legend('q = 0.01', 'q = 0.1', 'q = 1', 'q = 10', 'q = 100')

% Create a figure comparing all 3-state Doppler estimates with the truth.
figure()
% Plot every 3-state Doppler estimate generated by the process-noise sweep.
plot(t, fd_acc)
% Keep the figure active so the truth can be overlaid.
hold on
% Overlay the ground-truth Doppler reference.
plot(t, fd_truth, 'LineWidth',2, 'LineStyle','--')
% Label the curves associated with the selected process-noise values.
legend('q = 0.01', 'q = 0.1', 'q = 1', 'q = 10', 'q = 100')

% Create a figure comparing all 3-state Doppler-rate estimates with the truth.
figure()
% Plot every 3-state Doppler-rate estimate generated by the process-noise sweep.
plot(t, fddot_acc)
% Keep the figure active so the truth can be overlaid.
hold on
% Overlay the ground-truth Doppler-rate reference.
plot(t(2:end), dfdt, 'LineWidth',2, 'LineStyle','--')
% Label the curves associated with the selected process-noise values.
legend('q = 0.01', 'q = 0.1', 'q = 1', 'q = 10', 'q = 100')

% Create a figure for the final Doppler covariance of the 2-state filter.
figure()
% Plot the normalised final Doppler covariance versus process noise.
semilogx(q, sqrt(vel_cov(1,:))/sigma_fd)
% Title the covariance figure.
title('Final fd covariance for velocity KF')

% Create a figure for the final Doppler-rate covariance of the 2-state filter.
figure()
% Plot the final Doppler-rate covariance versus process noise.
semilogx(q, sqrt(vel_cov(2,:)))
% Title the covariance figure.
title('Final fddot covariance for velocity KF')

% Create a figure for the final Doppler covariance of the 3-state filter.
figure()
% Plot the normalised final Doppler covariance versus process noise.
semilogx(q, sqrt(acc_cov(1,:))/sigma_fd)
% Title the covariance figure.
title('Final fd covariance for acceleration KF')

% Create a figure for the final Doppler-rate covariance of the 3-state filter.
figure()
% Plot the final Doppler-rate covariance versus process noise.
semilogx(q, sqrt(acc_cov(2,:)))
% Title the covariance figure.
title('Final fddot covariance for acceleration KF')

% Create a figure for the Doppler RMSE of the 2-state filter.
figure()
% Plot the 2-state Doppler RMSE versus process noise.
semilogx(q, vel_rmse(1,:))
% Title the RMSE figure.
title('fd velocity KF RMSE')

% Create a figure for the Doppler-rate RMSE of the 2-state filter.
figure()
% Plot the 2-state Doppler-rate RMSE versus process noise.
semilogx(q, vel_rmse(2,:))
% Title the RMSE figure.
title('fddot velocity KF RMSE')

% Create a figure for the Doppler RMSE of the 3-state filter.
figure()
% Plot the 3-state Doppler RMSE versus process noise.
semilogx(q, acc_rmse(1,:))
% Title the RMSE figure.
title('fd acceleration KF RMSE')

% Create a figure for the Doppler-rate RMSE of the 3-state filter.
figure()
% Plot the 3-state Doppler-rate RMSE versus process noise.
semilogx(q, acc_rmse(2,:))
% Title the RMSE figure.
title('fddot acceleration KF RMSE')





